-- 创建归档分类表
DROP TABLE IF EXISTS `tb_archive_category`;
CREATE TABLE `tb_archive_category` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '分类ID',
  `category_code` varchar(100) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '分类代码',
  `category_name` varchar(200) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '分类名称',
  `parent_id` bigint DEFAULT NULL COMMENT '父级分类ID,NULL表示顶级分类',
  `level` tinyint NOT NULL DEFAULT 1 COMMENT '分类层级:1-一级分类,2-二级分类,3-三级分类',
  `sort_order` int NOT NULL DEFAULT 0 COMMENT '排序号,数字越小越靠前',
  `is_required` tinyint(1) NOT NULL DEFAULT 0 COMMENT '是否必填:0-否,1-是',
  `status` varchar(20) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'ACTIVE' COMMENT '状态: ACTIVE-激活, INACTIVE-停用, DELETED-删除',
  `description` text COLLATE utf8mb4_unicode_ci COMMENT '分类描述',
  `is_deleted` tinyint(1) NOT NULL DEFAULT 0 COMMENT '是否删除: 0-否, 1-是',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  `create_user_id` bigint DEFAULT NULL COMMENT '创建人ID',
  `update_user_id` bigint DEFAULT NULL COMMENT '更新人ID',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_category_code` (`category_code`),
  KEY `idx_parent_id` (`parent_id`),
  KEY `idx_level` (`level`),
  KEY `idx_sort_order` (`sort_order`),
  KEY `idx_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='归档分类表';

-- 创建归档记录表
DROP TABLE IF EXISTS `tb_archive_record`;
CREATE TABLE `tb_archive_record` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '记录ID',
  `case_id` bigint NOT NULL COMMENT '案件ID',
  `category_code` varchar(100) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '归档分类代码',
  `file_id` bigint NOT NULL COMMENT '文件ID(关联tb_file_record表)',
  `archive_no` varchar(50) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '归档编号,格式:AH-YYYYMMDD-XXXX',
  `file_title` varchar(500) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '文件标题',
  `file_description` text COLLATE utf8mb4_unicode_ci COMMENT '文件描述',
  `upload_user_id` bigint NOT NULL COMMENT '上传人ID',
  `upload_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '上传时间',
  `status` varchar(20) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'ACTIVE' COMMENT '记录状态: ACTIVE-激活, INACTIVE-停用, DELETED-删除',
  `is_confidential` tinyint(1) NOT NULL DEFAULT 0 COMMENT '是否机密:0-否,1-是',
  `access_level` varchar(20) COLLATE utf8mb4_unicode_ci DEFAULT 'INTERNAL' COMMENT '访问级别: PUBLIC-公开, INTERNAL-内部, CONFIDENTIAL-机密, TOP_SECRET-绝密',
  `version` int NOT NULL DEFAULT 1 COMMENT '版本号',
  `parent_version_id` bigint DEFAULT NULL COMMENT '父版本ID(用于版本回溯)',
  `is_deleted` tinyint(1) NOT NULL DEFAULT 0 COMMENT '是否删除: 0-否, 1-是',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  `create_user_id` bigint DEFAULT NULL COMMENT '创建人ID',
  `update_user_id` bigint DEFAULT NULL COMMENT '更新人ID',
  PRIMARY KEY (`id`),
  KEY `idx_case_id` (`case_id`),
  KEY `idx_category_code` (`category_code`),
  KEY `idx_file_id` (`file_id`),
  KEY `idx_archive_no` (`archive_no`),
  KEY `idx_upload_user_id` (`upload_user_id`),
  KEY `idx_upload_time` (`upload_time`),
  KEY `idx_status` (`status`),
  KEY `idx_access_level` (`access_level`),
  KEY `idx_version` (`version`),
  CONSTRAINT `fk_archive_record_case` FOREIGN KEY (`case_id`) REFERENCES `tb_bankrupt_case` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_archive_record_file` FOREIGN KEY (`file_id`) REFERENCES `tb_file_record` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='归档记录表';

